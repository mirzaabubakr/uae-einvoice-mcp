#!/usr/bin/env node
// Regenerates src/lib/codelists-data.ts from the official PINT AE resources.zip
// (https://docs.peppol.eu/poac/ae/pint-ae/resources.zip), unpacked at the path given as argv[2].
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.argv[2];
if (!root) {
  console.error("usage: node scripts/extract-codelists.mjs <unpacked-resources-dir>");
  process.exit(1);
}

const inv = join(root, "trn-invoice", "codelist");
const cn = join(root, "trn-creditnote", "codelist");

function rows(file) {
  const xml = readFileSync(file, "utf8");
  const out = [];
  for (const row of xml.matchAll(/<gc:Row>([\s\S]*?)<\/gc:Row>/g)) {
    const cols = {};
    for (const v of row[1].matchAll(
      /<gc:Value ColumnRef="([^"]+)">\s*<gc:SimpleValue>([\s\S]*?)<\/gc:SimpleValue>/g,
    )) {
      cols[v[1]] = v[2].replace(/\s+/g, " ").trim();
    }
    // The published AE tax category list spells "N" with a Greek capital Nu; the Schematron uses Latin N.
    if (cols.id) cols.id = cols.id.replace(/\u039d/g, "N");
    out.push(cols);
  }
  return out;
}

const decode = (s) =>
  s
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'");

function map(file) {
  return Object.fromEntries(rows(file).map((r) => [r.id, decode(r.name ?? r.description ?? "")]));
}

const lists = {
  TAX_CATEGORY_CODES: map(join(inv, "Aligned-TaxCategoryCodes.gc")),
  TAX_EXEMPTION_REASON_CODES: map(join(inv, "Aligned-TaxExemptionCodes.gc")),
  CREDIT_NOTE_REASON_CODES: map(join(cn, "CreditReason.gc")),
  PAYMENT_MEANS_CODES: map(join(inv, "UNCL4461.gc")),
  INVOICE_TYPE_CODES: map(join(inv, "UNCL1001-inv.gc")),
  CREDIT_NOTE_TYPE_CODES: map(join(cn, "UNCL1001-cn.gc")),
  ITEM_TYPE_CODES: map(join(inv, "ItemType.gc")),
  BILLING_FREQUENCY_CODES: map(join(inv, "FreqBilling.gc")),
  RCM_GOODS_TYPE_CODES: map(join(inv, "GoodsType.gc")),
  TRANSACTION_TYPE_FLAGS: map(join(inv, "transactiontype.gc")),
  ALLOWANCE_REASON_CODES: map(join(inv, "UNCL5189.gc")),
  CHARGE_REASON_CODES: map(join(inv, "UNCL7161.gc")),
  ELECTRONIC_ADDRESS_SCHEMES: map(join(inv, "eas.gc")),
  CURRENCY_CODES: map(join(inv, "ISO4217.gc")),
  COUNTRY_CODES: map(join(inv, "ISO3166.gc")),
  UNIT_CODES: map(join(inv, "UNECERec20.gc")),
};

let out = `// Generated by scripts/extract-codelists.mjs from the official PINT AE 1.0.4 resources.zip. Do not edit.\n`;
out += `export const CODELIST_SOURCE = "PINT AE Billing 1.0.4 (docs.peppol.eu/poac/ae/pint-ae/resources.zip)";\n\n`;
for (const [name, values] of Object.entries(lists)) {
  out += `export const ${name}: Readonly<Record<string, string>> = ${JSON.stringify(values, null, 1)};\n\n`;
}
writeFileSync(new URL("../src/lib/codelists-data.ts", import.meta.url), out);
console.log(
  Object.entries(lists)
    .map(([k, v]) => `${k}: ${Object.keys(v).length}`)
    .join("\n"),
);
