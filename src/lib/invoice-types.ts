export type InvoiceDocumentType = "tax_invoice" | "commercial_invoice" | "credit_note";

/** BTAE-15 / BTAE-16 legal registration identifier type. */
export type LegalRegistrationType = "TL" | "EID" | "PAS" | "CD";

/** The eight BTAE-02 transaction type flags, in code-string position order. */
export interface TransactionFlagsInput {
  freeTradeZone?: boolean;
  deemedSupply?: boolean;
  marginScheme?: boolean;
  summaryInvoice?: boolean;
  continuousSupply?: boolean;
  disclosedAgentBilling?: boolean;
  ecommerce?: boolean;
  exports?: boolean;
}

export interface AddressInput {
  addressLine?: string;
  cityOrEmirate?: string;
  /** IBT-039 / IBT-054 / IBT-079: AUH, DXB, SHJ, UAQ, FUJ, AJM or RAK when the country is AE. */
  countrySubdivision?: string;
  postalZone?: string;
  countryCode?: string;
}

export interface PartyInput extends AddressInput {
  legalName?: string;
  tradeName?: string;
  /** 15-digit VAT TRN (IBT-031 seller / IBT-048 buyer). */
  trn?: string;
  /** 10-digit TIN: Peppol endpoint under scheme 0235, and IBT-032 for sellers without a TRN. */
  tin?: string;
  /** IBT-030 / IBT-047 legal registration identifier, e.g. trade licence number. */
  legalRegistrationId?: string;
  legalRegistrationType?: LegalRegistrationType;
  /** BTAE-12 / BTAE-11: issuing authority, required when the type is TL. */
  legalRegistrationAuthority?: string;
  /** BTAE-18 / BTAE-19: ISO 3166 country of issue, required when the type is PAS. */
  passportIssuingCountry?: string;
  contactName?: string;
  email?: string;
  phone?: string;
  /** Override for the electronic address, e.g. "0235:1234567890" or a predefined "0235:9900000099". */
  peppolId?: string;
}

export interface InvoiceLineInput {
  id?: string;
  name?: string;
  /** IBT-154 item description (mandatory). */
  description?: string;
  quantity?: number;
  unitCode?: string;
  netAmount?: number;
  /** IBT-146 item net price. */
  unitPrice?: number;
  /** IBT-148 item gross price; defaults to the net price (no price discount). */
  grossPrice?: number;
  /** IBT-149 item price base quantity; defaults to 1. */
  priceBaseQuantity?: number;
  taxCategoryCode?: string;
  taxPercent?: number;
  /** IBT-186 exemption reason code, required on exempt (E) lines. */
  exemptionReasonCode?: string;
  /** BTAE-08 VAT line amount in AED; derived as netAmount × taxPercent when the invoice is in AED. */
  vatAmountAed?: number;
  /** BTAE-10 invoice line amount in AED (net + VAT); derived when the invoice is in AED. */
  lineAmountAed?: number;
  /** BTAE-13 item type: G (goods), S (services) or B (both). */
  itemType?: "G" | "S" | "B";
  /** IBT-158 HS classification, required for goods. */
  hsCode?: string;
  /** BTAE-17 service accounting code, required for services. */
  serviceAccountingCode?: string;
  /** BTAE-09 type of goods or services under reverse charge. */
  rcmGoodsType?: string;
  /** IBT-157 item standard identifier (GTIN, scheme 0160), required on reverse-charge lines. */
  standardItemId?: string;
}

export interface TaxBreakdownInput {
  taxableAmount?: number;
  taxAmount?: number;
  taxCategoryCode?: string;
  taxPercent?: number;
  exemptionReason?: string;
  exemptionReasonCode?: string;
}

export interface InvoiceDataInput {
  documentType?: InvoiceDocumentType;
  invoiceNumber?: string;
  /** BTAE-07 unique identifier (UUID); generated by generate_pint_ae_xml when absent. */
  uuid?: string;
  issueDate?: string;
  dueDate?: string;
  currencyCode?: string;
  /** IBT-006 tax accounting currency; must be AED when present. */
  taxCurrencyCode?: string;
  /** BTAE-04 exchange rate from the invoice currency to AED. */
  exchangeRate?: number;
  customizationId?: string;
  profileId?: string;
  /** 380 tax invoice, 480 out of scope of tax (commercial), 381 credit note, 81 credit note for 480. */
  typeCode?: string;
  /** BTAE-02 as an 8-character 0/1 string, e.g. "00000000". Takes precedence over transactionFlags. */
  transactionType?: string;
  transactionFlags?: TransactionFlagsInput;
  /** IBT-081 payment means type code (UNCL4461 AE subset). */
  paymentMeansCode?: string;
  /** IBT-084 payment account identifier, required for credit transfer (30). */
  paymentAccountId?: string;
  buyerReference?: string;
  periodStart?: string;
  periodEnd?: string;
  taxPointDate?: string;
  /** IBT-025 preceding invoice reference — required on credit notes unless the reason is VD. */
  billingReference?: string;
  billingReferenceDate?: string;
  /** BTAE-03 credit note reason code. */
  creditNoteReasonCode?: string;
  /** BTAE-01 beneficiary ID (free trade zone flag). */
  beneficiaryId?: string;
  /** BTAE-14 principal ID (disclosed agent billing flag). */
  principalId?: string;
  /** Deliver-to address, required for the e-commerce and exports flags. */
  deliverTo?: AddressInput;
  seller?: PartyInput;
  buyer?: PartyInput;
  lineNetTotal?: number;
  taxExclusiveTotal?: number;
  taxTotal?: number;
  /** IBT-111 total VAT in the tax accounting currency (AED). */
  taxTotalAed?: number;
  /** BTAE-20 invoice total with VAT in AED. */
  totalWithVatAed?: number;
  taxInclusiveTotal?: number;
  allowanceTotal?: number;
  chargeTotal?: number;
  prepaidAmount?: number;
  payableAmount?: number;
  taxBreakdown?: TaxBreakdownInput[];
  lines?: InvoiceLineInput[];
}
